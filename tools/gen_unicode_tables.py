"""Generate HALean/Template/Unicode.lean: the two Unicode tables the template
engine needs, from the Python that Home Assistant runs on.

  * the code points `str.isprintable()` rejects (what `repr()` escapes), as
    ranges;
  * the first code point (digit zero) of every run of ten decimal digits
    (category Nd, what `int()` and `float()` accept and `re`'s `\\d` matches).

Run with HA's Python (3.14, Unicode 16.0):
    /path/to/ha/.venv/bin/python tools/gen_unicode_tables.py > HALean/Template/Unicode.lean
"""

import sys
import unicodedata

ranges = []
start = None
for c in range(0x110000):
    np = not chr(c).isprintable()
    if np and start is None:
        start = c
    if not np and start is not None:
        ranges.append((start, c - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

starts = [c for c in range(0x110000)
          if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0]
# every Nd code point lies in a run of ten consecutive digits 0..9
nd = [c for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd"]
assert len(nd) == 10 * len(starts)
assert all(unicodedata.decimal(chr(s + i)) == i for s in starts for i in range(10))
# and the decimal property is exactly Nd
assert all(unicodedata.decimal(chr(c), None) is None or unicodedata.category(chr(c)) == "Nd"
           for c in range(0x110000))


def chunks(items, n):
    for i in range(0, len(items), n):
        yield items[i:i + n]


out = sys.stdout
v = sys.version_info
out.write(f"""/-
  Unicode tables for the template engine, generated by
  `tools/gen_unicode_tables.py` from Python {v.major}.{v.minor}.{v.micro} (Unicode {unicodedata.unidata_version}),
  the Python Home Assistant 2026.10.4 runs on. Do not edit by hand.
-/
namespace HALean.Template

/-- The code points for which `str.isprintable()` is false (what `repr()`
escapes), as `lo-hi` hexadecimal ranges. -/
def NONPRINTABLE_TEXT : String :=
""")
parts = [f"{a:x}-{b:x}" for a, b in ranges]
lines = [",".join(ch) for ch in chunks(parts, 12)]
out.write("  " + " ++\n  ".join(f'"{ln},"' for ln in lines) + "\n\n")
out.write("""/-- The digit zero of every run of ten decimal digits (category `Nd`). -/
def ND_ZEROS_TEXT : String :=
""")
parts = [f"{a:x}" for a in starts]
lines = [",".join(ch) for ch in chunks(parts, 16)]
out.write("  " + " ++\n  ".join(f'"{ln},"' for ln in lines) + "\n\n")
out.write("end HALean.Template\n")
